/* ===========================================================================
   Generates sample-site/fixtures.js from fixtures-data.js plus the real
   PageContent.csv (files/PageContent.csv), converted to the
   { key: { text, image } } map that getPageContent() returns.

   Run:  node sample-site/make-fixtures.js
   =========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');
const data = require('./fixtures-data.js');

function parseCSV(text) {
  const rows = []; let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else q = false; }
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c === '\r') { /* ignore */ }
    else field += c;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((v) => v !== ''));
}

const csvPath = path.join(__dirname, '..', 'files', 'PageContent.csv');
const csv = parseCSV(fs.readFileSync(csvPath, 'utf8'));
const head = csv[0];
const pageContent = {};
csv.slice(1).forEach((r) => {
  const o = {}; head.forEach((h, i) => { o[h] = r[i] || ''; });
  if (!o.contentKey) return;
  pageContent[o.contentKey] = { text: (o.text || '').trim(), image: o.image || o.imageUrl || '' };
});

let extra = {};
const extraPath = path.join(__dirname, 'fixtures-cms.json');   // optional: real CMS pull
if (fs.existsSync(extraPath)) {
  extra = JSON.parse(fs.readFileSync(extraPath, 'utf8'));
  console.log('merging real CMS data from fixtures-cms.json: ' + Object.keys(extra).join(', '));
}

const fixtures = Object.assign({ pageContent }, data, extra);
if (extra.pageContent) fixtures.pageContent = Object.assign({}, pageContent, extra.pageContent);

fs.writeFileSync(path.join(__dirname, 'fixtures.js'),
  '/* generated by make-fixtures.js -- do not edit by hand */\n' +
  'window.ARISE_FIXTURES = ' + JSON.stringify(fixtures, null, 2) + ';\n');
console.log('fixtures.js written: ' + Object.keys(fixtures).join(', ') +
  ' | pageContent keys: ' + Object.keys(fixtures.pageContent).length);
